const areEqual = (
    prev: JSX.IntrinsicElements['group'],
    next: JSX.IntrinsicElements['group']
) => {
    const prevPos = prev.position as number[] | undefined
    const nextPos = next.position as number[] | undefined
    const prevRot = prev.rotation as number[] | undefined
    const nextRot = next.rotation as number[] | undefined
    const prevScale = prev.scale as number[] | number | undefined
    const nextScale = next.scale as number[] | number | undefined

    const vecEqual = (a?: number[], b?: number[]) => {
        if (!a && !b) return true
        if (!a || !b) return false
        return a[0] === b[0] && a[1] === b[1] && a[2] === b[2]
    }

    const scaleEqual = (a?: number[] | number, b?: number[] | number) => {
        if (a === b) return true
        if (typeof a === 'number' || typeof b === 'number') return false
        return vecEqual(a as number[] | undefined, b as number[] | undefined)
    }

    return vecEqual(prevPos, nextPos) && vecEqual(prevRot, nextRot) && scaleEqual(prevScale, nextScale)
}

